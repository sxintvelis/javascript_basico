// =========================================
// EJERCICIO 1 - ÁREA DE UN TRIÁNGULO
// Fórmula: AT = (B * H) / 2
// AT = Área del triángulo
// B = Base del triángulo
// H = Altura del triángulo
// =========================================

// Cambiar estos valores para probar el código con diferentes entradas.

const base = 56; // Base del triángulo (número entero)
const altura = 9; // Altura del triángulo (número entero)

// Calcular el área del triángulo, el cual es base * altura / 2
const areaTriangulo = (base * altura) / 2;

// Mostrar el resultado en la consola
console.log("==== Área del Triángulo ====");
console.log("La base es: ", base); // Imprime la base del triángulo
console.log("La altura es: ", altura); // Imprime la altura del triángulo
console.log("El área del triángulo es: ", areaTriangulo); // Imprime el área del triángulo